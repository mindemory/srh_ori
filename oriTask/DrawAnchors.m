function DrawAnchors(x, y, boxSize, segmentSize, parameters, screen, lineWidth)
 % Top-left edge
Screen('FrameRect', screen.win, parameters.boxColor, ...
    [x - boxSize/2, y - boxSize/2, x - boxSize/2 + segmentSize, y - boxSize/2 + lineWidth], lineWidth);
Screen('FrameRect', screen.win, parameters.boxColor, ...
    [x - boxSize/2, y - boxSize/2, x - boxSize/2 + lineWidth, y - boxSize/2 + segmentSize], lineWidth);
% Top-right edge
Screen('FrameRect', screen.win, parameters.boxColor, ...
    [x + boxSize/2 - segmentSize, y - boxSize/2, x + boxSize/2, y - boxSize/2 + lineWidth], lineWidth);
Screen('FrameRect', screen.win, parameters.boxColor, ...
    [x + boxSize/2 - lineWidth, y - boxSize/2, x + boxSize/2, y - boxSize/2 + segmentSize], lineWidth);
% Bottom-left edge
Screen('FrameRect', screen.win, parameters.boxColor, ...
    [x - boxSize/2, y + boxSize/2 - segmentSize, x - boxSize/2 + lineWidth, y + boxSize/2], lineWidth);
Screen('FrameRect', screen.win, parameters.boxColor, ...
    [x - boxSize/2, y + boxSize/2 - lineWidth, x - boxSize/2 + segmentSize, y + boxSize/2], lineWidth);
% Bottom-right edge
Screen('FrameRect', screen.win, parameters.boxColor, ...
    [x + boxSize/2 - segmentSize, y + boxSize/2 - lineWidth, x + boxSize/2, y + boxSize/2], lineWidth);
Screen('FrameRect', screen.win, parameters.boxColor, ...
    [x + boxSize/2 - lineWidth, y + boxSize/2 - segmentSize, x + boxSize/2, y + boxSize/2], lineWidth);
end